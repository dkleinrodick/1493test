function parseRoute(routeText) {
    // Split by " - "
    const parts = routeText.split(' - ');
    if (parts.length !== 2) return null;

    const origin = parts[0].trim();
    const destination = parts[1].trim();

    // Find airport codes for these cities
    let originCode = null;
    let destCode = null;

    // Check if it's already a code
    for (const [code, city] of Object.entries(airports)) {
        if (city === origin || origin.includes(code)) {
            originCode = code;
        }
        if (city === destination || destination.includes(code)) {
            destCode = code;
        }
    }

    if (originCode && destCode) {
        return { origin: originCode, destination: destCode };
    }

    return null;
}

