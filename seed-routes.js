function seedRoutes() {
    console.log('Seeding routes database...');

    let successCount = 0;
    let failCount = 0;

    frontierRoutes.forEach(route => {
        const parts = route.split(' - ');
        if (parts.length !== 2) {
            console.log(`Skipping malformed route: ${route}`);
            failCount++;
            return;
        }

        const originCity = parts[0].trim();
        const destCity = parts[1].trim();

        const originCode = cityToCode[originCity];
        const destCode = cityToCode[destCity];

        if (originCode && destCode) {
            try {
                upsertRoute(originCode, destCode);
                successCount++;
            } catch (error) {
                console.error(`Error inserting route ${originCode} -> ${destCode}:`, error.message);
                failCount++;
            }
        } else {
            if (!originCode) console.log(`Unknown origin city: ${originCity}`);
            if (!destCode) console.log(`Unknown destination city: ${destCity}`);
            failCount++;
        }
    });

    console.log(`\nSeeding complete!`);
    console.log(`✅ Successfully added: ${successCount} routes`);
    console.log(`❌ Failed: ${failCount} routes`);

    return successCount;
}

